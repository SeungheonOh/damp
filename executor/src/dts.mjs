// TypeScript declarations for a compiled contract, generated from contract.json.
//
// The types describe what `makeContract(spec, witnesses)` returns and expects:
// argument and result types of every circuit, and the witnesses the caller
// must supply.

const ident = (s) => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : JSON.stringify(s));

/** Collect named struct shapes, keyed by name; structurally different shapes with one name get a suffix. */
function collectStructs(spec) {
  const byName = new Map();
  const names = new Map(); // JSON of shape -> type name
  const visit = (shape) => {
    switch (shape.kind) {
      case 'struct': {
        shape.fields.forEach(visit);
        const key = JSON.stringify(shape);
        if (names.has(key)) return;
        let name = shape.name, n = 1;
        while (byName.has(name)) name = `${shape.name}_${++n}`;
        byName.set(name, shape);
        names.set(key, name);
        break;
      }
      case 'tuple': shape.elems.forEach(visit); break;
      case 'vector': visit(shape.elem); break;
      default: break;
    }
  };
  const circuits = [...spec.circuits, ...(spec.constructor ? [spec.constructor] : [])];
  for (const c of circuits) {
    c.args.forEach((a) => visit(a.shape));
    visit(c.result);
    for (const s of c.body) if (s.kind === 'witness') visit(s.shape);
  }
  for (const f of spec.ledger) {
    for (const k of ['shape', 'key', 'value', 'elem']) if (f.type[k]) visit(f.type[k]);
  }
  return { byName, names };
}

function typeOf(shape, names) {
  switch (shape.kind) {
    case 'field': case 'uint': return 'bigint';
    case 'bool': return 'boolean';
    case 'bytes': return 'Uint8Array';
    case 'enum': return 'number';
    case 'struct': return names.get(JSON.stringify(shape));
    case 'tuple': return `[${shape.elems.map((e) => typeOf(e, names)).join(', ')}]`;
    case 'vector': return `${typeOf(shape.elem, names)}[]`;
    default: throw new Error(`unknown shape ${shape.kind}`);
  }
}

const describe = (shape) => {
  switch (shape.kind) {
    case 'uint': return ` /* at most ${shape.max} */`;
    case 'bytes': return ` /* ${shape.length} bytes */`;
    case 'enum': return ` /* variant 0..${shape.max} */`;
    case 'vector': return ` /* length ${shape.length} */`;
    default: return '';
  }
};

/** Witnesses the executor implements itself (executor.mjs `RESERVED_WITNESSES`). */
const BUILTIN_WITNESSES = new Set(['ownPublicKey', 'createZswapInput', 'createZswapOutput']);

/** Witness signatures, taken from the first use of each witness the caller supplies. */
function witnessesOf(spec) {
  const seen = new Map();
  const circuits = [...spec.circuits, ...(spec.constructor ? [spec.constructor] : [])];
  for (const c of circuits) {
    for (const s of c.body) {
      if (s.kind === 'witness' && !seen.has(s.name) && !BUILTIN_WITNESSES.has(s.name)) seen.set(s.name, s);
    }
  }
  return [...seen.values()];
}

export function generateDts(spec) {
  const { byName, names } = collectStructs(spec);
  const out = [];
  out.push(`// Generated by Damp from contract "${spec.name}". Do not edit.`);
  out.push(`import type * as rt from '@midnight-ntwrk/compact-runtime';`, '');

  for (const [name, shape] of byName) {
    out.push(`export type ${name} = {`);
    shape.fields.forEach((f, i) => out.push(`  ${ident(shape.fieldNames[i])}: ${typeOf(f, names)};${describe(f)}`));
    out.push('};', '');
  }

  out.push('/** Private inputs the caller supplies. Each returns the next private state and the value. */');
  out.push('export type Witnesses<PS> = {');
  for (const w of witnessesOf(spec)) {
    const args = w.args.map((_, i) => `, arg${i}: bigint`).join('');
    out.push(`  ${ident(w.name)}(context: rt.WitnessContext<unknown, PS>${args}): [PS, ${typeOf(w.shape, names)}];`);
  }
  out.push('};', '');

  out.push('export type CircuitResult<PS, R> = {');
  out.push('  result: R;', '  context: rt.CircuitContext<PS>;', '  gasCost: unknown;', '  proofData: rt.ProofData;', '};', '');

  const signature = (c) => {
    const args = c.args.map((a) => `, ${ident(a.name)}: ${typeOf(a.shape, names)}`).join('');
    return `(context: rt.CircuitContext<PS>${args}): Promise<CircuitResult<PS, ${typeOf(c.result, names)}>>`;
  };
  const block = (title, doc, circuits) => {
    out.push(`/** ${doc} */`, `export type ${title}<PS> = {`);
    for (const c of circuits) out.push(`  ${ident(c.name)}${signature(c)};`);
    out.push('};', '');
  };
  block('Circuits', 'Every exported circuit.', spec.circuits);
  block('ProvableCircuits', 'The circuits whose calls are proved: those that touch the ledger.', spec.circuits.filter((c) => c.proof));

  const ctorArgs = spec.constructor
    ? spec.constructor.args.map((a) => `, ${ident(a.name)}: ${typeOf(a.shape, names)}`).join('')
    : '';
  out.push('export type Contract<PS> = {');
  out.push('  witnesses: Witnesses<PS>;');
  out.push('  circuits: Circuits<PS>;');
  out.push('  impureCircuits: ProvableCircuits<PS>;');
  out.push('  provableCircuits: ProvableCircuits<PS>;');
  out.push(`  initialState(context: rt.ConstructorContext<PS>${ctorArgs}): Promise<rt.ConstructorResult<PS>>;`);
  out.push('};', '');
  out.push('/** Build the contract from its `contract.json` and witness implementations. */');
  out.push('export declare function makeContract<PS>(spec: unknown, witnesses: Witnesses<PS>): Contract<PS>;');
  return out.join('\n') + '\n';
}
