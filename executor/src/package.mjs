// Package a contract built by Damp as the directory layout midnight-js
// expects from a compiled contract:
//
//   contract/index.js        exports `Contract`, `ledger`, and what a caller's
//                            runtime loads for a cross-contract call:
//                            `circuitSignatures`, `expectedVk`, `declaredInterfaces`
//   contract/index.d.ts      TypeScript declarations
//   contract/executor.mjs    the generic executor, copied so that it loads the
//                            same compact-runtime as the application
//   contract/contract.json   the contract data
//   zkir/<circuit>.zkir, .bzkir
//   keys/<circuit>.prover, .verifier
//   compiler/contract-info.json       names the runtime version
//   compiler/contract-manifest.json   size and SHA-256 of every file
//
// The input directory is what `Damp.cli --keys` writes.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateDts } from './dts.mjs';

/** The compact-runtime version the executor is written against. */
export const RUNTIME_VERSION = '0.21.0';
/** The Compact language version whose semantics Damp mirrors. */
export const LANGUAGE_VERSION = '0.28.0';
export const COMPILER_VERSION = 'damp-0.1.0';

const here = path.dirname(fileURLToPath(import.meta.url));
const sha256 = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const f of fs.readdirSync(from)) fs.copyFileSync(path.join(from, f), path.join(to, f));
}

const indexJs = (spec, expectedVk) => `// Generated by Damp from contract "${spec.name}". Do not edit.
import { makeContract, ledgerView, circuitSignatures as signaturesOf, declaredInterfaces as interfacesOf } from './executor.mjs';

export const spec = ${JSON.stringify(spec)};

/** The contract, in the shape midnight-js expects of a compiled contract. */
export class Contract {
  constructor(witnesses = {}) {
    return makeContract(spec, witnesses);
  }
}

/** The contract's public state as JS values. */
export const ledger = (state) => ledgerView(spec, state);

/** What a caller's runtime checks this module against before calling one of its
 *  circuits (cross-contract calls; docs/calls.md), as in compactc's modules:
 *  the circuits' types, and the SHA-256 of each verifier key in keys/. */
export const circuitSignatures = signaturesOf(spec);
export const expectedVk = ${JSON.stringify(expectedVk, null, 2)};

/** The contract types this contract calls other contracts through. */
export const declaredInterfaces = interfacesOf(spec);
`;

/**
 * @param src  directory written by Damp (contract.json, zkir/, keys/)
 * @param out  directory to create
 */
export function packageContract(src, out) {
  const spec = JSON.parse(fs.readFileSync(path.join(src, 'contract.json'), 'utf-8'));
  const provable = spec.circuits.filter((c) => c.proof).map((c) => c.name);
  for (const c of provable) {
    for (const f of [`keys/${c}.prover`, `keys/${c}.verifier`, `zkir/${c}.bzkir`]) {
      if (!fs.existsSync(path.join(src, f))) {
        throw new Error(`${f} is missing: build the contract with --keys before packaging`);
      }
    }
  }

  fs.rmSync(out, { recursive: true, force: true });
  copyDir(path.join(src, 'keys'), path.join(out, 'keys'));
  copyDir(path.join(src, 'zkir'), path.join(out, 'zkir'));
  fs.mkdirSync(path.join(out, 'contract'), { recursive: true });
  fs.copyFileSync(path.join(src, 'contract.json'), path.join(out, 'contract', 'contract.json'));
  fs.copyFileSync(path.join(here, 'executor.mjs'), path.join(out, 'contract', 'executor.mjs'));
  const expectedVk = Object.fromEntries(provable.map((c) =>
    [c, sha256(fs.readFileSync(path.join(src, 'keys', `${c}.verifier`)))]));
  fs.writeFileSync(path.join(out, 'contract', 'index.js'), indexJs(spec, expectedVk));
  const dts = generateDts(spec).replace(
    /export declare function makeContract[^\n]*\n/,
    'export declare class Contract<PS> {\n  constructor(witnesses: Witnesses<PS>);\n}\n' +
      'export declare function ledger(state: rt.StateValue | rt.ChargedState): Record<string, unknown>;\n' +
      'export declare const circuitSignatures: rt.CircuitSignatures;\n' +
      'export declare const expectedVk: Readonly<Record<string, string>>;\n' +
      'export declare const declaredInterfaces: rt.DeclaredInterfaces;\n');
  fs.writeFileSync(path.join(out, 'contract', 'index.d.ts'), dts);

  const versions = {
    'compiler-version': COMPILER_VERSION,
    'language-version': LANGUAGE_VERSION,
    'runtime-version': RUNTIME_VERSION,
  };
  fs.mkdirSync(path.join(out, 'compiler'), { recursive: true });
  const info = {
    ...versions,
    circuits: spec.circuits.map((c) => ({
      name: c.name, pure: !c.proof, proof: !!c.proof, arguments: c.args.map((a) => ({ name: a.name })),
    })),
    ledger: spec.ledger.map((f) => ({ name: f.name, index: f.index, storage: f.type.kind })),
  };
  fs.writeFileSync(path.join(out, 'compiler', 'contract-info.json'), JSON.stringify(info, null, 2) + '\n');

  const manifest = { 'manifest-version': '1', ...versions };
  for (const d of ['compiler', 'contract', 'zkir', 'keys']) {
    manifest[d] = { type: 'directory' };
    for (const f of fs.readdirSync(path.join(out, d)).sort()) {
      const bytes = fs.readFileSync(path.join(out, d, f));
      manifest[d][f] = { type: 'file', size: bytes.length, hash: sha256(bytes) };
    }
  }
  fs.writeFileSync(path.join(out, 'compiler', 'contract-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  return { dir: out, spec };
}
